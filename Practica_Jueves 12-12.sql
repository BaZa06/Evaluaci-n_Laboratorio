CREATE DATABASE bd_laboratorio_orm;

-- Crear el esquema
CREATE SCHEMA IF NOT EXISTS catalogos;

-- Eliminar primero la tabla que tiene la clave foránea
DROP TABLE IF EXISTS catalogos.equipo CASCADE;
DROP TABLE IF EXISTS catalogos.tipo_equipo CASCADE;

-- Crear la tabla de tipos de equipo
CREATE TABLE catalogos.tipo_equipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(250) NOT NULL UNIQUE,
    descripcion VARCHAR(300)
);

-- Crear la tabla de equipos
CREATE TABLE catalogos.equipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(250) NOT NULL UNIQUE,
    nombre VARCHAR(250) NOT NULL,
    marca VARCHAR(250) NOT NULL,
    estado VARCHAR(250) NOT NULL,
    cantidad INTEGER NOT NULL,
    id_tipo BIGINT NOT NULL,

    CONSTRAINT fk_equipo_tipo
        FOREIGN KEY (id_tipo)
        REFERENCES catalogos.tipo_equipo(id),

    CONSTRAINT chk_cantidad
        CHECK (cantidad >= 0),

    CONSTRAINT ck_equipo_estado
        CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio'))
);

